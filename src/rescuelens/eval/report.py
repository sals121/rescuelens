"""Turn the JSON outputs of `rescuelens eval` into results/<date>/README.md + plots."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from rescuelens.data.heridal import ground_truth
from rescuelens.eval.detection import load_preds
from rescuelens.eval.metrics import pr_curve

_LABELS = {
    "yolo26s_full": "YOLO26s COCO, full frame",
    "yolo26s_sahi": "YOLO26s COCO + SAHI",
    "rescuelens-yolo26s-heridal_full": "Fine-tuned, full frame",
    "rescuelens-yolo26s-heridal_sahi": "Fine-tuned + SAHI",
}


def _f(x: Any, nd: int = 3) -> str:  # noqa: ANN401
    return "-" if x is None else f"{x:.{nd}f}"


def detector_table(rows: list[dict[str, Any]]) -> str:
    head = (
        "| Detector | AP50 | AP50-95 | Precision | Recall | F1 | FP / image | Best F1 (conf) "
        "| s / frame |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|\n"
    )
    body = "".join(
        f"| {_LABELS.get(r['run'], r['run'])} | {_f(r['ap50'])} | {_f(r['ap50_95'])} "
        f"| {_f(r['precision'])} | {_f(r['recall'])} | {_f(r['f1'])} | {_f(r['fp_per_image'], 2)} "
        f"| {_f(r['best_f1'])} ({r['best_f1_conf']:.2f}) | {_f(r['s_per_frame'], 2)} |\n"
        for r in rows
    )
    return head + body


def llm_table(results: list[dict[str, Any]]) -> str:
    head = (
        "| Candidates | Model | Variant | Precision | Recall | F1 | FP / image | AP50 "
        "| Cost (USD) | p50 latency |\n|---|---|---|---:|---:|---:|---:|---:|---:|---:|\n"
    )
    out = head
    for res in results:
        s, m = res["summary"], res["metrics"]
        for key, label in (
            ("yolo", "YOLO alone"),
            ("yolo+claude_filter", "YOLO + Claude (filter)"),
            ("yolo+claude_rescored", "YOLO + Claude (re-ranked)"),
        ):
            row = m[key]
            cost = _f(s["cost_usd"], 2) if key != "yolo" else "-"
            lat = _f(s["latency_p50_s"], 1) + " s" if key != "yolo" and s["latency_p50_s"] else "-"
            out += (
                f"| {s['candidates']} (conf ≥ {res['conf']}) | {res['model']} | {label} "
                f"| {_f(row['precision'])} | {_f(row['recall'])} | {_f(row['f1'])} "
                f"| {_f(row['fp_per_image'], 2)} | {_f(row['ap50'])} | {cost} | {lat} |\n"
            )
    return out


def plot_pr(results_dir: Path, data_dir: Path, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    gts = ground_truth(data_dir)
    fig, ax = plt.subplots(figsize=(7, 5), dpi=150)
    for tag, label in _LABELS.items():
        path = results_dir / "preds" / f"{tag}.json"
        if not path.exists():
            continue
        preds, _ = load_preds(path)
        curve = pr_curve(preds, gts)
        ax.plot([c[2] for c in curve], [c[1] for c in curve], label=label, linewidth=2)
    ax.set(xlabel="Recall", ylabel="Precision", xlim=(0, 1), ylim=(0, 1.02))
    ax.set_title("HERIDAL test set, 101 full frames (IoU 0.5)")
    ax.grid(alpha=0.3)
    ax.legend(loc="lower left")
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)


def write_report(results_dir: Path, data_dir: Path) -> Path:
    rows = json.loads((results_dir / "detector.json").read_text(encoding="utf-8"))
    llm = [
        json.loads(p.read_text(encoding="utf-8")) for p in sorted(results_dir.glob("llm_*.json"))
    ]
    plot_pr(results_dir, data_dir, results_dir / "pr_curve.png")
    md = [
        f"# RescueLens evaluation — {results_dir.name}",
        "",
        "Official HERIDAL test set: 101 full-resolution frames, 337 annotated people. "
        "A detection is correct when IoU ≥ 0.5 with an unmatched ground-truth box. "
        "Precision, recall, F1 and FP/image are at detector confidence ≥ 0.25. "
        "Generated by `rescuelens eval report` from the JSON files in this folder.",
        "",
        "## Detector",
        "",
        detector_table(rows),
        "![Precision-recall curves](pr_curve.png)",
        "",
    ]
    if llm:
        md += [
            "## Claude verification",
            "",
            "Each candidate is sent to Claude as in production (crop + context, prompt "
            "`verify_v1`, strict JSON schema). *Filter* drops candidates Claude rejects; "
            "*re-ranked* scores every candidate by Claude's p(person). Unverified candidates "
            "are kept (fail open). Costs are API list-price equivalents.",
            "",
            llm_table(llm),
        ]
    path = results_dir / "README.md"
    path.write_text("\n".join(md), encoding="utf-8")
    return path
